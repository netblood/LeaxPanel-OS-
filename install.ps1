# ============================================================================
# LeaxPanel(os) - Windows Installer (PowerShell)
# ============================================================================
# One-command install from GitHub:
#   iwr -useb https://raw.githubusercontent.com/netblood/LeaxPanel-OS-/main/install.ps1 | iex
#
# This script:
#   1. Checks Node.js & npm
#   2. Generates secure random passwords for all services
#   3. Creates .env with generated credentials
#   4. Creates docker-compose.override.yml to wire passwords into Docker
#   5. Starts PostgreSQL, Redis, Minio via Docker
#   6. Runs database migrations and seeds
#   7. Displays all service credentials
# ============================================================================

$ErrorActionPreference = 'Continue'
$ProgressPreference = 'SilentlyContinue'

# When run via `iwr -useb | iex`, download project files to a temp directory
if (-not $PSCommandPath -or -not (Test-Path $PSCommandPath)) {
    Write-Host "[*] Downloading project files from GitHub..." -ForegroundColor Cyan
    $InstallDir = [System.IO.Path]::GetTempPath() + "LeaxPanelInstall"
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
    Set-Location $InstallDir
    if (Get-Command git -ErrorAction SilentlyContinue) {
        git clone --depth 1 https://github.com/netblood/LeaxPanel-OS-.git .
    } else {
        Invoke-WebRequest -Uri "https://github.com/netblood/LeaxPanel-OS-/archive/refs/heads/main.zip" -OutFile "$InstallDir/master.zip"
        Expand-Archive -Path "$InstallDir/master.zip" -DestinationPath $InstallDir -Force
        $subDir = Get-ChildItem $InstallDir | Where-Object { $_.PSIsContainer } | Select-Object -First 1
        Move-Item -Path "$($subDir.FullName)\*" -Destination $InstallDir -Force
        Remove-Item -Path "$InstallDir/master.zip" -Force
        Remove-Item -Path $subDir.FullName -Recurse -Force
    }
}

Write-Host ""
Write-Host "============================================================"
Write-Host "  LeaxPanel(os) - Complete Cloud Operating System"
Write-Host "  Windows Installer (PowerShell) - Auto Setup"
Write-Host "============================================================"
Write-Host ""

# ---- Password generator ----
function Generate-RandomString {
    param([int]$Length = 16)
    $chars = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'.ToCharArray()
    -join ((1..$Length) | ForEach-Object { $chars | Get-Random })
}

# ---- Generate all credentials ----
Write-Host "[*] Generating secure service credentials..." -ForegroundColor Cyan
$DB_PASSWORD     = (Generate-RandomString 16)
$REDIS_PASSWORD  = (Generate-RandomString 16)
$MINIO_PASSWORD  = (Generate-RandomString 16)
$SESSION_SECRET  = (Generate-RandomString 32)
$JWT_SECRET      = (Generate-RandomString 32)
$ENCRYPTION_KEY  = (Generate-RandomString 32)
Write-Host "    Credentials generated." -ForegroundColor Green

# Check Node.js
Write-Host "[1/9] Checking Node.js..."
$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) {
    Write-Host "ERROR: Node.js is not installed or not in PATH." -ForegroundColor Red
    Write-Host "Please install Node.js 22+ from https://nodejs.org/"
    pause
    exit 1
}
Write-Host ("Node.js found: " + $node.Source)

# Check npm
Write-Host "[2/9] Checking npm..."
$npm = Get-Command npm -ErrorAction SilentlyContinue
if (-not $npm) {
    Write-Host "ERROR: npm is not available." -ForegroundColor Red
    pause
    exit 1
}
Write-Host ("npm found: " + $npm.Source)

# Check Docker (optional - for PostgreSQL, Redis, Minio)
Write-Host "[3/9] Checking Docker..."
$docker = Get-Command docker -ErrorAction SilentlyContinue
$DOCKER_AVAILABLE = $false
if ($docker) {
    Write-Host "Docker found."
    $DOCKER_AVAILABLE = $true
} else {
    Write-Host "WARNING: Docker not found. PostgreSQL/Redis/Minio will not be auto-started." -ForegroundColor Yellow
    Write-Host "Please install Docker Desktop from https://www.docker.com/products/docker-desktop/"
}

# Create .env with generated credentials
Write-Host "[4/9] Setting up environment configuration (.env)..."
$envContent = @"
# LeaxPanel(os) Environment Configuration
# Auto-generated by installer - DO NOT COMMIT TO VERSION CONTROL
NODE_ENV=development
PORT=3000
HOST=0.0.0.0

# Database
DATABASE_URL=postgresql://leaxos:${DB_PASSWORD}@localhost:5432/leaxos
DB_HOST=localhost
DB_PORT=5432
DB_NAME=leaxos
DB_USER=leaxos
DB_PASSWORD=${DB_PASSWORD}

# Redis
REDIS_HOST=localhost
REDIS_PORT=6379
REDIS_PASSWORD=${REDIS_PASSWORD}

# Minio (Object Storage)
MINIO_HOST=localhost
MINIO_PORT=9000
MINIO_CONSOLE_PORT=9001
MINIO_ROOT_USER=leaxos
MINIO_ROOT_PASSWORD=${MINIO_PASSWORD}

# Session
SESSION_SECRET=${SESSION_SECRET}
SESSION_MAX_AGE=86400000

# JWT
JWT_SECRET=${JWT_SECRET}
JWT_EXPIRES_IN=7d

# Encryption (AES-256-GCM, must be 32 chars)
ENCRYPTION_KEY=${ENCRYPTION_KEY}

# AI Providers (users can configure their own)
OPENAI_API_KEY=
ANTHROPIC_API_KEY=
GOOGLE_API_KEY=
DEEPSEEK_API_KEY=
GROK_API_KEY=
OPENROUTER_API_KEY=

# Email (Stalwart / SMTP)
SMTP_HOST=localhost
SMTP_PORT=25
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM=noreply@leaxos.local

# Billing (disabled by default)
STRIPE_SECRET_KEY=
STRIPE_PUBLISHABLE_KEY=
STRIPE_WEBHOOK_SECRET=
PAYPAL_CLIENT_ID=
PAYPAL_CLIENT_SECRET=
PAYPAL_MODE=sandbox

# Cloudflare
CLOUDFLARE_API_TOKEN=
CLOUDFLARE_ACCOUNT_ID=
CLOUDFLARE_ZONE_ID=

# Docker
DOCKER_HOST=/var/run/docker.sock

# Security
RATE_LIMIT_WINDOW_MS=900000
RATE_LIMIT_MAX=100
FAIL2BAN_ENABLED=false
CROWDSEC_ENABLED=false

# Monitoring
MONITORING_INTERVAL=30000

# Backup
BACKUP_ENABLED=true
BACKUP_RETENTION_DAYS=30
"@
Set-Content -Path .env -Value $envContent -Encoding UTF8
Write-Host "    .env created with auto-generated credentials." -ForegroundColor Green

# Create docker-compose.override.yml to wire credentials into Docker services
Write-Host "[5/9] Creating Docker Compose override with credentials..."
$overrideContent = @"
version: '3.8'
services:
  postgres:
    environment:
      POSTGRES_PASSWORD: ${DB_PASSWORD}
  redis:
    command: redis-server --requirepass ${REDIS_PASSWORD}
    healthcheck:
      test: ["CMD", "redis-cli", "-a", "${REDIS_PASSWORD}", "ping"]
  minio:
    environment:
      MINIO_ROOT_PASSWORD: ${MINIO_PASSWORD}
  leaxos:
    environment:
      - DB_PASSWORD=${DB_PASSWORD}
      - REDIS_PASSWORD=${REDIS_PASSWORD}
"@
Set-Content -Path "docker-compose.override.yml" -Value $overrideContent -Encoding UTF8
Write-Host "    docker-compose.override.yml created." -ForegroundColor Green

# Install npm dependencies
Write-Host "[6/9] Installing npm dependencies..."
npm install
if ($LASTEXITCODE -ne 0) {
    Write-Host "ERROR: npm install failed." -ForegroundColor Red
    pause
    exit 1
}
Write-Host "Dependencies installed successfully."

# Start Docker services if available
if ($DOCKER_AVAILABLE) {
    Write-Host "[7/9] Starting Docker services (PostgreSQL, Redis, Minio)..."
    $composeUp = docker compose up -d postgres redis minio 2>$null
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Trying docker-compose..." -ForegroundColor Yellow
        docker-compose up -d postgres redis minio 2>$null
        if ($LASTEXITCODE -ne 0) {
            Write-Host "WARNING: Could not start Docker services. You may need to start them manually." -ForegroundColor Yellow
            $DOCKER_AVAILABLE = $false
        }
    }

    # Wait for PostgreSQL to be ready
    if ($DOCKER_AVAILABLE) {
        Write-Host "[8/9] Waiting for PostgreSQL to be ready..."
        $attempts = 0
        $pgReady = $false
        while ($attempts -lt 60) {
            $ready = docker compose exec -T postgres pg_isready -U leaxos -d leaxos 2>$null
            if ($LASTEXITCODE -eq 0) {
                $pgReady = $true
                break
            }
            $attempts++
            Start-Sleep -Seconds 2
        }
        if (-not $pgReady) {
            Write-Host "WARNING: PostgreSQL did not become ready in time. Migrations may fail." -ForegroundColor Yellow
        } else {
            Write-Host "PostgreSQL is ready."

            # Run database migrations
            Write-Host "[9/9] Running database migrations..."
            if (node migrations/run.js) {
                Write-Host "Migrations completed successfully."

                # Run database seeds
                Write-Host "Running database seeds..."
                if (node seeds/run.js) {
                    Write-Host "Seeds completed successfully."
                } else {
                    Write-Host "WARNING: Seeds failed. Run manually later with: node seeds/run.js" -ForegroundColor Yellow
                }
            } else {
                Write-Host "WARNING: Migrations failed. Run manually later with: node migrations/run.js" -ForegroundColor Yellow
            }
        }
    }
} else {
    Write-Host "[7/9] Skipping Docker services (Docker not available)."
    Write-Host "[8/9] Skipping migrations (PostgreSQL not available)."
    Write-Host "[9/9] Skipping seeds (PostgreSQL not available)."
}

# Optional: Fix vulnerabilities
Write-Host "Running npm audit fix (optional)..."
npm audit fix --force 2>$null | Out-Null

# ---- Summary ----
Write-Host ""
Write-Host "============================================================"
Write-Host "  Installation complete!"
Write-Host "============================================================"
Write-Host ""
Write-Host "To start the server, run: run.bat"
Write-Host "Or manually: node server.js"
Write-Host ""
Write-Host "============================================================"
Write-Host "  SERVICE CREDENTIALS (auto-generated)"
Write-Host "============================================================"
Write-Host ""
Write-Host "  PostgreSQL:"
Write-Host "    Host:     localhost:5432"
Write-Host "    Database: leaxos"
Write-Host "    User:     leaxos"
Write-Host "    Password: $DB_PASSWORD"
Write-Host ""
Write-Host "  Redis:"
Write-Host "    Host:     localhost:6379"
Write-Host "    Password: $REDIS_PASSWORD"
Write-Host ""
Write-Host "  Minio (Object Storage):"
Write-Host "    Host:     localhost:9000"
Write-Host "    Console:  localhost:9001"
Write-Host "    User:     leaxos"
Write-Host "    Password: $MINIO_PASSWORD"
Write-Host ""
Write-Host "  Session Secret:   $SESSION_SECRET"
Write-Host "  JWT Secret:       $JWT_SECRET"
Write-Host "  Encryption Key:   $ENCRYPTION_KEY"
Write-Host ""
Write-Host "All credentials have been saved to .env"
Write-Host "Default admin account: owner@leaxos.local"
Write-Host ""
pause
