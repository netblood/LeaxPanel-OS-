#!/bin/bash
# ============================================================================
# LeaxPanel(os) - Linux/macOS Installer
# ============================================================================
# One-command install from GitHub:
#   curl -fsSL https://raw.githubusercontent.com/netblood/LeaxPanel-OS-/main/install.sh | bash
#
# This script:
#   1. Checks Node.js & npm
#   2. Generates secure random passwords for all services
#   3. Creates .env with generated credentials
#   4. Creates docker-compose.override.yml to wire passwords into Docker
#   5. Starts PostgreSQL, Redis, Minio via Docker
#   6. Runs database migrations and seeds
#   7. Displays all service credentials
# ============================================================================

set -e

echo ""
echo "============================================================"
echo "  LeaxPanel(os) - Complete Cloud Operating System"
echo "  Linux/macOS Installer - Auto Setup"
echo "============================================================"
echo ""

# ---- Password generator ----
generate_password() {
    local len=${1:-16}
    LC_ALL=C tr -dc 'a-zA-Z0-9' < /dev/urandom | head -c "$len"
    echo
}

# ---- Generate all credentials ----
echo "[*] Generating secure service credentials..."
DB_PASSWORD=$(generate_password 16)
REDIS_PASSWORD=$(generate_password 16)
MINIO_PASSWORD=$(generate_password 16)
SESSION_SECRET=$(generate_password 32)
JWT_SECRET=$(generate_password 32)
ENCRYPTION_KEY=$(generate_password 32)
echo "    Credentials generated."

# Check Node.js
echo "[1/9] Checking Node.js..."
if ! command -v node &> /dev/null; then
    echo "ERROR: Node.js is not installed or not in PATH."
    echo "Please install Node.js 22+ from https://nodejs.org/"
    exit 1
fi
node --version

# Check npm
echo "[2/9] Checking npm..."
if ! command -v npm &> /dev/null; then
    echo "ERROR: npm is not available."
    exit 1
fi
npm --version

# Check Docker (optional - for PostgreSQL, Redis, Minio)
echo "[3/9] Checking Docker..."
DOCKER_AVAILABLE=0
if command -v docker &> /dev/null; then
    echo "Docker found."
    DOCKER_AVAILABLE=1
else
    echo "WARNING: Docker not found. PostgreSQL/Redis/Minio will not be auto-started."
    echo "Please install Docker from https://docs.docker.com/engine/install/"
fi

# Create .env with generated credentials
echo "[4/9] Setting up environment configuration (.env)..."
cat > .env <<ENVEOF
# LeaxPanel(os) Environment Configuration
# Auto-generated by installer - DO NOT COMMIT TO VERSION CONTROL
NODE_ENV=development
PORT=3000
HOST=0.0.0.0

# Database
DATABASE_URL=postgresql://leaxos:${DB_PASSWORD}@localhost:5432/leaxos
DB_HOST=localhost
DB_PORT=5432
DB_NAME=leaxos
DB_USER=leaxos
DB_PASSWORD=${DB_PASSWORD}

# Redis
REDIS_HOST=localhost
REDIS_PORT=6379
REDIS_PASSWORD=${REDIS_PASSWORD}

# Minio (Object Storage)
MINIO_HOST=localhost
MINIO_PORT=9000
MINIO_CONSOLE_PORT=9001
MINIO_ROOT_USER=leaxos
MINIO_ROOT_PASSWORD=${MINIO_PASSWORD}

# Session
SESSION_SECRET=${SESSION_SECRET}
SESSION_MAX_AGE=86400000

# JWT
JWT_SECRET=${JWT_SECRET}
JWT_EXPIRES_IN=7d

# Encryption (AES-256-GCM, must be 32 chars)
ENCRYPTION_KEY=${ENCRYPTION_KEY}

# AI Providers (users can configure their own)
OPENAI_API_KEY=
ANTHROPIC_API_KEY=
GOOGLE_API_KEY=
DEEPSEEK_API_KEY=
GROK_API_KEY=
OPENROUTER_API_KEY=

# Email (Stalwart / SMTP)
SMTP_HOST=localhost
SMTP_PORT=25
SMTP_USER=
SMTP_PASSWORD=
SMTP_FROM=noreply@leaxos.local

# Billing (disabled by default)
STRIPE_SECRET_KEY=
STRIPE_PUBLISHABLE_KEY=
STRIPE_WEBHOOK_SECRET=
PAYPAL_CLIENT_ID=
PAYPAL_CLIENT_SECRET=
PAYPAL_MODE=sandbox

# Cloudflare
CLOUDFLARE_API_TOKEN=
CLOUDFLARE_ACCOUNT_ID=
CLOUDFLARE_ZONE_ID=

# Docker
DOCKER_HOST=/var/run/docker.sock

# Security
RATE_LIMIT_WINDOW_MS=900000
RATE_LIMIT_MAX=100
FAIL2BAN_ENABLED=false
CROWDSEC_ENABLED=false

# Monitoring
MONITORING_INTERVAL=30000

# Backup
BACKUP_ENABLED=true
BACKUP_RETENTION_DAYS=30
ENVEOF
echo "    .env created with auto-generated credentials."

# Create docker-compose.override.yml to wire credentials into Docker services
echo "[5/9] Creating Docker Compose override with credentials..."
cat > docker-compose.override.yml <<OVERRIDEEOF
version: '3.8'
services:
  postgres:
    environment:
      POSTGRES_PASSWORD: ${DB_PASSWORD}
  redis:
    command: redis-server --requirepass ${REDIS_PASSWORD}
    healthcheck:
      test: ["CMD", "redis-cli", "-a", "${REDIS_PASSWORD}", "ping"]
  minio:
    environment:
      MINIO_ROOT_PASSWORD: ${MINIO_PASSWORD}
  leaxos:
    environment:
      - DB_PASSWORD=${DB_PASSWORD}
      - REDIS_PASSWORD=${REDIS_PASSWORD}
OVERRIDEEOF
echo "    docker-compose.override.yml created."

# Install npm dependencies
echo "[6/9] Installing npm dependencies..."
npm install
echo "Dependencies installed successfully."

# Start Docker services if available
if [ "$DOCKER_AVAILABLE" -eq 1 ]; then
    echo "[7/9] Starting Docker services (PostgreSQL, Redis, Minio)..."
    if command -v docker compose &> /dev/null; then
        docker compose up -d postgres redis minio
    elif command -v docker-compose &> /dev/null; then
        docker-compose up -d postgres redis minio
    else
        echo "WARNING: Neither 'docker compose' nor 'docker-compose' found."
        DOCKER_AVAILABLE=0
    fi

    # Wait for PostgreSQL to be ready
    if [ "$DOCKER_AVAILABLE" -eq 1 ]; then
        echo "[8/9] Waiting for PostgreSQL to be ready..."
        ATTEMPTS=0
        until docker compose exec -T postgres pg_isready -U leaxos -d leaxos &> /dev/null || \
              docker-compose exec -T postgres pg_isready -U leaxos -d leaxos &> /dev/null; do
            ATTEMPTS=$((ATTEMPTS + 1))
            if [ "$ATTEMPTS" -ge 60 ]; then
                echo "WARNING: PostgreSQL did not become ready in time. Migrations may fail."
                break
            fi
            sleep 2
        done
        if [ "$ATTEMPTS" -lt 60 ]; then
            echo "PostgreSQL is ready."

            # Run database migrations
            echo "[9/9] Running database migrations..."
            if node migrations/run.js; then
                echo "Migrations completed successfully."

                # Run database seeds
                echo "Running database seeds..."
                if node seeds/run.js; then
                    echo "Seeds completed successfully."
                else
                    echo "WARNING: Seeds failed. Run manually later with: node seeds/run.js"
                fi
            else
                echo "WARNING: Migrations failed. Run manually later with: node migrations/run.js"
            fi
        fi
    fi
else
    echo "[7/9] Skipping Docker services (Docker not available)."
    echo "[8/9] Skipping migrations (PostgreSQL not available)."
    echo "[9/9] Skipping seeds (PostgreSQL not available)."
fi

# Optional: Fix vulnerabilities
echo "Running npm audit fix (optional)..."
npm audit fix --force 2>/dev/null || true

# ---- Summary ----
echo ""
echo "============================================================"
echo "  Installation complete!"
echo "============================================================"
echo ""
echo "To start the server, run: ./run.sh"
echo "Or manually: node server.js"
echo ""
echo "============================================================"
echo "  SERVICE CREDENTIALS (auto-generated)"
echo "============================================================"
echo ""
echo "  PostgreSQL:"
echo "    Host:     localhost:5432"
echo "    Database: leaxos"
echo "    User:     leaxos"
echo "    Password: ${DB_PASSWORD}"
echo ""
echo "  Redis:"
echo "    Host:     localhost:6379"
echo "    Password: ${REDIS_PASSWORD}"
echo ""
echo "  Minio (Object Storage):"
echo "    Host:     localhost:9000"
echo "    Console:  localhost:9001"
echo "    User:     leaxos"
echo "    Password: ${MINIO_PASSWORD}"
echo ""
echo "  Session Secret:   ${SESSION_SECRET}"
echo "  JWT Secret:       ${JWT_SECRET}"
echo "  Encryption Key:   ${ENCRYPTION_KEY}"
echo ""
echo "All credentials have been saved to .env"
echo "Default admin account: owner@leaxos.local"
echo ""
